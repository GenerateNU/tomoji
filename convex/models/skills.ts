export type Skill = CatalogOption;

/** Lists the predefined skill options, optionally matching a name or display label. */
export function listSkills(search?: string): Skill[] {
  return listCatalogOptions(SKILLS, search);
}

/** Resolves a known skill name or display label; rejects unsupported values with invalid_skill. */
export function requireSkill(input: string): string {
  return requireCatalogOption(SKILLS, input, "skill");
}

/** Validates and deduplicates skill selections in the caller's order. */
export function requireSkills(names: string[]): string[] {
  return [...new Set(names.map(requireSkill))];
}
