export type Brand = "stripe" | "x" | "google" | "apple";

type BrandLogoProps = Omit<ComponentProps<"svg">, "children"> & {
  brand: Brand;
  /** Stripe indigo and Google four-color; otherwise the logo is one color. */
  colored?: boolean;
};

const VIEW_BOX: Record<Brand, string> = {
  stripe: "0 0 39.0004 17",
  x: "0 0 16 16",
  google: "0 0 18 18",
  apple: "0 0 18 18",
};

const SIZE: Record<Brand, string> = {
  stripe: "h-4.25 w-auto",
  x: "size-4",
  google: "size-4.5",
  apple: "size-4.5",
};

const NAME: Record<Brand, string> = { stripe: "Stripe", x: "X", google: "Google", apple: "Apple" };

/** A brand logo, labelled with the brand's name. */
export function BrandLogo({ brand, colored = false, className, ...props }: BrandLogoProps) {
  const paths =
    brand === "google"
      ? GOOGLE_PATHS.map(({ d, color }) => ({ d, fill: colored ? color : "currentColor" }))
      : (brand === "stripe" ? STRIPE_PATHS : brand === "x" ? X_PATHS : APPLE_PATHS).map((d) => ({
          d,
          fill: brand === "stripe" && colored ? "#635bff" : "currentColor",
        }));
  return (
    <svg
      role="img"
      aria-label={NAME[brand]}
      viewBox={VIEW_BOX[brand]}
      className={cn("shrink-0", SIZE[brand], className)}
      {...props}
    >
      {paths.map(({ d, fill }) => (
        <path key={d} d={d} fill={fill} />
      ))}
    </svg>
  );
}
